#!/usr/bin/env node
/**
 * Generate the shader-analysis contract both WASM sides read, from one source:
 *
 *   src/contracts/bind_group0.json        shaderUsageFlags (bit + @binding per flag)
 *   src/contracts/workgroup_dispatch.json unparsedFallback (dispatch when
 *                                         @workgroup_size cannot be resolved)
 *
 * Outputs (committed):
 *   src/wasm/bridge/_contracts.ts   import-free constants; wgslAnalysis.ts packs
 *                                   loadShader's usageBits with them, and the TS
 *                                   renderer's ShaderCompilation.ts shares them
 *   wasm_renderer/wasm_contracts.h  the same bits + fallback for C++, which takes
 *                                   workgroup size and usage from loadShader
 *                                   instead of parsing WGSL itself
 *
 * Usage: node scripts/gen-wasm-contracts.js [--check]
 *   (none)  — write both files (`npm run gen:wasm-contracts`)
 *   --check — exit 1 when either committed file differs (run by verify:device-policy)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const BIND_GROUP0 = path.join(ROOT, 'src', 'contracts', 'bind_group0.json');
const DISPATCH = path.join(ROOT, 'src', 'contracts', 'workgroup_dispatch.json');
const TS_REL = 'src/wasm/bridge/_contracts.ts';
const HEADER_REL = 'wasm_renderer/wasm_contracts.h';

const readJson = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));

/** Validate and return [{ name, bit, binding }] in contract order. Throws on a malformed table. */
function loadUsageFlags(bindGroup0 = readJson(BIND_GROUP0)) {
  const table = bindGroup0.shaderUsageFlags;
  if (!table || typeof table !== 'object') throw new Error('bind_group0.json: shaderUsageFlags missing');
  const declared = new Set((bindGroup0.bindings || []).map((b) => b.binding));
  const seenBits = new Set();
  const seenBindings = new Set();
  return Object.entries(table).map(([name, spec]) => {
    if (!/^[A-Za-z_]\w*$/.test(name)) throw new Error(`shaderUsageFlags: bad flag name "${name}"`);
    const { bit, binding } = spec || {};
    if (!Number.isInteger(bit) || bit <= 0 || (bit & (bit - 1)) !== 0 || bit > 0x40000000) {
      throw new Error(`shaderUsageFlags.${name}: bit must be a single power of two below 2^31`);
    }
    if (seenBits.has(bit)) throw new Error(`shaderUsageFlags.${name}: bit ${bit} is used twice`);
    if (!declared.has(binding)) throw new Error(`shaderUsageFlags.${name}: @binding(${binding}) is not in bindings`);
    if (seenBindings.has(binding)) throw new Error(`shaderUsageFlags.${name}: @binding(${binding}) is used twice`);
    seenBits.add(bit);
    seenBindings.add(binding);
    return { name, bit, binding };
  });
}

function loadFallback(dispatch = readJson(DISPATCH)) {
  const f = dispatch.unparsedFallback || {};
  if (!Number.isInteger(f.x) || !Number.isInteger(f.y) || f.x < 1 || f.y < 1) {
    throw new Error('workgroup_dispatch.json: unparsedFallback.x/y must be positive integers');
  }
  return { x: f.x, y: f.y };
}

const HEAD =
  'GENERATED by scripts/gen-wasm-contracts.js from src/contracts/bind_group0.json\n' +
  'shaderUsageFlags and workgroup_dispatch.json unparsedFallback. Do not edit:\n' +
  'change the JSON and run `npm run gen:wasm-contracts`.';

function emitTs(flags, fallback) {
  const lines = HEAD.split('\n').map((l) => `// ${l}`);
  lines.push(
    '',
    '/** loadShader usageBits, one per optional per-frame copy (bind_group0.json shaderUsageFlags). */',
    'export const SHADER_USAGE_BITS = {',
    ...flags.map((f) => `  ${f.name}: ${f.bit},`),
    '} as const;',
    '',
    '/** @binding each usage flag is detected from. */',
    'export const SHADER_USAGE_BINDINGS = {',
    ...flags.map((f) => `  ${f.name}: ${f.binding},`),
    '} as const;',
    '',
    'export type ShaderUsageFlag = keyof typeof SHADER_USAGE_BITS;',
    '',
    '/** Every usage bit set: what C++ assumes for a shader the bridge did not analyze. */',
    `export const SHADER_USAGE_ALL = ${flags.reduce((a, f) => a | f.bit, 0)};`,
    '',
    '/** Dispatch size when @workgroup_size cannot be resolved (workgroup_dispatch.json). */',
    `export const WORKGROUP_UNPARSED_FALLBACK = { x: ${fallback.x}, y: ${fallback.y} } as const;`,
    '',
  );
  return lines.join('\n');
}

function emitHeader(flags, fallback) {
  const lines = HEAD.split('\n').map((l) => `// ${l}`);
  lines.push(
    '//',
    '// loadShader(id, wgsl, workgroupX, workgroupY, usageBits) carries the bridge',
    '// analysis (src/wasm/bridge/wgslAnalysis.ts); C++ never parses WGSL for it.',
    '#pragma once',
    '',
    '#include <cstdint>',
    '',
    'namespace wasm_contracts {',
    '',
    ...flags.map((f) => `constexpr uint32_t kUsage_${f.name} = ${f.bit}u; // @binding(${f.binding})`),
    `constexpr uint32_t kUsageAll = ${flags.reduce((a, f) => a | f.bit, 0)}u;`,
    '',
    `constexpr uint32_t kWorkgroupFallbackX = ${fallback.x}u;`,
    `constexpr uint32_t kWorkgroupFallbackY = ${fallback.y}u;`,
    '',
    '} // namespace wasm_contracts',
    '',
  );
  return lines.join('\n');
}

function generate() {
  const flags = loadUsageFlags();
  const fallback = loadFallback();
  return { [TS_REL]: emitTs(flags, fallback), [HEADER_REL]: emitHeader(flags, fallback) };
}

function main() {
  const check = process.argv.includes('--check');
  const out = generate();
  let stale = 0;
  for (const [rel, text] of Object.entries(out)) {
    const abs = path.join(ROOT, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (current === text) continue;
    if (check) {
      console.error(`✗ ${rel} is stale — run npm run gen:wasm-contracts`);
      stale++;
    } else {
      fs.writeFileSync(abs, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('✓ wasm contracts (_contracts.ts, wasm_contracts.h) in sync');
}

if (require.main === module) {
  try {
    main();
  } catch (err) {
    console.error(`✗ ${err.message}`);
    process.exit(1);
  }
}

module.exports = { loadUsageFlags, loadFallback, emitTs, emitHeader, generate, TS_REL, HEADER_REL };
