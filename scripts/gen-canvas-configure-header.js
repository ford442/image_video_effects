#!/usr/bin/env node
/**
 * Generate wasm_renderer/canvas_configure.h from src/contracts/canvas_configure.json,
 * so the C++ canvas configure reads the same capabilities object as TS
 * buildCanvasConfigureOptions().
 * Usage: node scripts/gen-canvas-configure-header.js [--check]
 *   (none)  — write the header (committed; `npm run gen:canvas-configure`)
 *   --check — exit 1 if the committed header differs from the contract
 *             (run by verify:device-policy and build.sh)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONTRACT_PATH = path.join(ROOT, 'src', 'contracts', 'canvas_configure.json');

function loadContract(file = CONTRACT_PATH) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function headerPath(contract) {
  return path.join(ROOT, contract.cpp.header);
}

function usageExpr(contract, names) {
  return names.map((name) => {
    const e = contract.cpp.usageEnums[name];
    if (!e) throw new Error(`canvas_configure.json cpp.usageEnums has no entry for ${name}`);
    return e;
  }).join(' | ');
}

function enumFor(table, key, label) {
  const e = table[key];
  if (!e) throw new Error(`canvas_configure.json ${label} has no entry for '${key}'`);
  return e;
}

function renderHeader(contract) {
  const { cpp } = contract;
  const wasmCaps = Object.entries(contract.optIn)
    .filter(([, cap]) => (cap.backends || []).includes('wasm'))
    .map(([name]) => name);
  const tsOnly = Object.entries(contract.optIn)
    .filter(([, cap]) => !(cap.backends || []).includes('wasm'))
    .map(([name]) => name);
  // JS GPUTextureUsage and C WGPUTextureUsage share bit values (spec); the EM_JS
  // configures take the C value as a plain number, so pin each one here.
  const bitAsserts = Object.entries(cpp.usageEnums).map(([name, e]) => {
    const bit = contract.usageBits[name];
    if (bit === undefined) throw new Error(`canvas_configure.json usageBits has no entry for ${name}`);
    return `static_assert(${e} == 0x${bit.toString(16)}, "GPUTextureUsage.${name} bit");`;
  });
  return [
    '// GENERATED by scripts/gen-canvas-configure-header.js from',
    '// src/contracts/canvas_configure.json. Do not edit: change the JSON and run',
    '// `npm run gen:canvas-configure`. verify:device-policy fails when this is stale.',
    '//',
    '// The WASM canvas configure (JS_CreateSurfaceFromCanvas, JS_ProbeCanvasCopySrc,',
    '// ConfigureSurface in device.cpp) reads these; TS buildCanvasConfigureOptions()',
    '// reads the same JSON.',
    `// WASM capabilities: ${wasmCaps.join(', ') || 'none'}. TS-only: ${tsOnly.join(', ') || 'none'}.`,
    '#pragma once',
    '',
    '#include <webgpu/webgpu.h>',
    '',
    'namespace canvas_configure {',
    '',
    `inline constexpr int kContractVersion = ${contract.version};`,
    '',
    '// Default path.',
    `inline constexpr WGPUTextureUsage kUsage = ${usageExpr(contract, contract.usage)};`,
    `inline constexpr WGPUCompositeAlphaMode kAlphaMode = ${enumFor(cpp.alphaModeEnums, contract.alphaMode, 'cpp.alphaModeEnums')};`,
    `inline constexpr const char* kAlphaModeJs = "${contract.alphaMode}";`,
    `inline constexpr WGPUPresentMode kPresentMode = ${enumFor(cpp.presentModeEnums, contract.presentModeWasm, 'cpp.presentModeEnums')};`,
    '',
    '// optIn.copySrc: full swapchain usage while the capture opt-in is on.',
    `inline constexpr WGPUTextureUsage kCopySrcUsage = ${usageExpr(contract, contract.optIn.copySrc.usage)};`,
    '',
    ...bitAsserts,
    '',
    '}  // namespace canvas_configure',
    '',
  ].join('\n');
}

function main(argv) {
  const contract = loadContract();
  const out = headerPath(contract);
  const want = renderHeader(contract);
  if (argv.includes('--check')) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (have !== want) {
      console.error(`❌ ${contract.cpp.header} is stale; run: npm run gen:canvas-configure`);
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(out, want);
  console.log(`wrote ${contract.cpp.header}`);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { loadContract, renderHeader, headerPath };
