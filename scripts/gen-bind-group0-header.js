#!/usr/bin/env node
/**
 * Generate wasm_renderer/bind_group0.h from src/contracts/bind_group0.json, so
 * the C++ compute bind group layout reads the same binding table (and the same
 * sample-type rules) as the TS layout in src/renderer/webgpu/pipeline.ts.
 * Usage: node scripts/gen-bind-group0-header.js [--check]
 *   (none)  — write the header (committed; `npm run gen:bind-group0`)
 *   --check — exit 1 if the committed header differs from the contract
 *             (run by verify:device-policy)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONTRACT_PATH = path.join(ROOT, 'src', 'contracts', 'bind_group0.json');

function loadContract(file = CONTRACT_PATH) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function headerPath(contract) {
  return path.join(ROOT, contract.cpp.header);
}

/** read-only-storage-buffer -> ReadOnlyStorageBuffer, depthRead -> DepthRead */
function pascal(name) {
  return name
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

/** Bindings must be dense 0..n-1 and every kind must be declared. */
function validate(contract) {
  contract.bindings.forEach((b, i) => {
    if (b.binding !== i) throw new Error(`bind_group0.json bindings must be dense: index ${i} is @binding(${b.binding})`);
    if (!contract.kinds[b.kind]) throw new Error(`bind_group0.json @binding(${b.binding}) has unknown kind "${b.kind}"`);
  });
  for (const [kind, spec] of Object.entries(contract.kinds)) {
    const st = spec.texture?.sampleType;
    if (st && !contract.sampleTypes[st]) throw new Error(`bind_group0.json kind ${kind} has unknown sampleType "${st}"`);
  }
}

function sampleRule(spec) {
  const st = spec.texture?.sampleType;
  if (st === 'color-format') return 'SampleRule::ColorFormat';
  if (st === 'unfilterable-float') return 'SampleRule::UnfilterableFloat';
  return 'SampleRule::NotSampled';
}

function renderHeader(contract) {
  validate(contract);
  const kinds = Object.keys(contract.kinds);
  const resources = [...new Set(contract.bindings.map((b) => b.resource))];
  const width = Math.max(...contract.bindings.map((b) => pascal(b.kind).length));
  const rows = contract.bindings.map((b) => {
    const kind = `BindingKind::${pascal(b.kind)},`.padEnd(width + 14);
    return `    { ${String(b.binding).padStart(2)}, ${kind} BindingResource::${pascal(b.resource)} },  // ${b.name}`;
  });
  return [
    '// GENERATED by scripts/gen-bind-group0-header.js from',
    '// src/contracts/bind_group0.json. Do not edit: change the JSON and run',
    '// `npm run gen:bind-group0`. verify:device-policy fails when this is stale.',
    '//',
    '// pipeline.cpp builds the compute bind group layout and every compute bind',
    '// group from kComputeBindings; TS pipeline.ts imports the same JSON.',
    '#pragma once',
    '',
    '#include <cstddef>',
    '#include <cstdint>',
    '',
    'namespace bind_group0 {',
    '',
    `inline constexpr int kContractVersion = ${contract.version};`,
    '',
    'enum class BindingKind : uint8_t {',
    ...kinds.map((k) => `    ${pascal(k)},`),
    '};',
    '',
    '// Which renderer object fills the binding. Input/Output are per-pass (the',
    "// slot's read/write textures); everything else is a shared global.",
    'enum class BindingResource : uint8_t {',
    ...resources.map((r) => `    ${pascal(r)},`),
    '};',
    '',
    '// How a sampled texture kind picks its sampleType (contract "sampleTypes").',
    '//   ColorFormat       — Float for rgba16float, or rgba32float + float32-filterable;',
    '//                       UnfilterableFloat otherwise.',
    '//   UnfilterableFloat — always UnfilterableFloat (r32float depth).',
    'enum class SampleRule : uint8_t { NotSampled, ColorFormat, UnfilterableFloat };',
    '',
    'constexpr SampleRule KindSampleRule(BindingKind kind) {',
    '    switch (kind) {',
    ...kinds.map((k) => `        case BindingKind::${pascal(k)}: return ${sampleRule(contract.kinds[k])};`),
    '    }',
    '    return SampleRule::NotSampled;',
    '}',
    '',
    'struct ComputeBinding {',
    '    uint32_t binding;',
    '    BindingKind kind;',
    '    BindingResource resource;',
    '};',
    '',
    'inline constexpr ComputeBinding kComputeBindings[] = {',
    ...rows,
    '};',
    `inline constexpr size_t kComputeBindingCount = ${contract.bindings.length};`,
    'static_assert(sizeof(kComputeBindings) / sizeof(kComputeBindings[0]) == kComputeBindingCount,',
    '              "kComputeBindings must match bind_group0.json");',
    '',
    '}  // namespace bind_group0',
    '',
  ].join('\n');
}

function main(argv) {
  const contract = loadContract();
  const out = headerPath(contract);
  const want = renderHeader(contract);
  if (argv.includes('--check')) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (have !== want) {
      console.error(`❌ ${contract.cpp.header} is stale; run: npm run gen:bind-group0`);
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(out, want);
  console.log(`wrote ${contract.cpp.header}`);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { loadContract, renderHeader, headerPath };
