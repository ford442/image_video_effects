#!/usr/bin/env node
/**
 * generate-shader-definition-types.mjs — derive everything that must track the schema from
 * src/contracts/shader_definition.schema.json:
 *
 *   src/types/ShaderDefinition.ts              TypeScript types (json-schema-to-typescript)
 *   src/contracts/shaderDefinition.validate.js  standalone ajv validator (no ajv at runtime)
 *
 * Both outputs are committed; `--check` regenerates in memory and fails on any difference
 * (used by scripts/verify-generated-sync.mjs). Run without flags to rewrite them.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SCHEMA_PATH = path.join(ROOT, 'src', 'contracts', 'shader_definition.schema.json');
export const TYPES_PATH = path.join(ROOT, 'src', 'types', 'ShaderDefinition.ts');
export const VALIDATOR_PATH = path.join(ROOT, 'src', 'contracts', 'shaderDefinition.validate.js');

const BANNER =
  '// Auto-generated by scripts/generate-shader-definition-types.mjs from\n' +
  '// src/contracts/shader_definition.schema.json. Do not edit — change the schema and re-run.\n';

export async function generate() {
  const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));

  const types = await compile(schema, 'ShaderDefinition', {
    bannerComment: '',
    additionalProperties: false,
    unreachableDefinitions: false,
    strictIndexSignatures: false,
    format: true,
    style: { singleQuote: true, semi: true, trailingComma: 'all', printWidth: 100 },
  });

  const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: false } });
  const validate = ajv.compile(schema);
  const validator =
    `/* eslint-disable */\n// @ts-nocheck\n${BANNER}` + standaloneCode(ajv, validate);

  return {
    [TYPES_PATH]: `${BANNER}${types.replace(/\s+$/, '')}\n`,
    [VALIDATOR_PATH]: `${validator.replace(/\s+$/, '')}\n`,
  };
}

async function main() {
  const check = process.argv.includes('--check');
  const outputs = await generate();
  let stale = 0;
  for (const [file, text] of Object.entries(outputs)) {
    const rel = path.relative(ROOT, file);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (check) {
      if (current !== text) {
        stale += 1;
        console.error(`generate-shader-definition-types: ${rel} is stale — run: node scripts/generate-shader-definition-types.mjs`);
      }
      continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`generate-shader-definition-types: wrote ${rel} (${text.length} bytes)`);
  }
  if (stale) process.exit(1);
  if (check) console.log('generate-shader-definition-types: up to date');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
