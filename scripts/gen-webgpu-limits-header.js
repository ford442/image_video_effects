#!/usr/bin/env node
/**
 * Generate wasm_renderer/webgpu_limits.h from src/contracts/webgpu_limits.json,
 * so the C++ adapter check and requiredLimits read the same numbers as the TS
 * policy (webgpuDevicePolicy.ts) instead of mirroring them by hand.
 * Usage: node scripts/gen-webgpu-limits-header.js [--check]
 *   (none)  — write the header (committed; `npm run gen:webgpu-limits`)
 *   --check — exit 1 if the committed header differs from the contract
 *             (run by verify:device-policy and build.sh)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONTRACT_PATH = path.join(ROOT, 'src', 'contracts', 'webgpu_limits.json');

function loadContract(file = CONTRACT_PATH) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function headerPath(contract) {
  return path.join(ROOT, contract.cpp.header);
}

/** maxTextureDimension2D -> kMaxTextureDimension2D */
function constName(key) {
  return `k${key[0].toUpperCase()}${key.slice(1)}`;
}

function constants(limits) {
  return Object.entries(limits).map(([key, value]) => {
    if (!Number.isInteger(value) || value < 0) throw new Error(`webgpu_limits.json ${key} must be a non-negative integer`);
    return `inline constexpr uint32_t ${constName(key)} = ${value};`;
  });
}

function renderHeader(contract) {
  return [
    '// GENERATED by scripts/gen-webgpu-limits-header.js from',
    '// src/contracts/webgpu_limits.json. Do not edit: change the JSON and run',
    '// `npm run gen:webgpu-limits`. verify:device-policy fails when this is stale.',
    '//',
    '// device.cpp CheckLimit() and requiredLimits read these; TS webgpuDevicePolicy.ts',
    '// imports the same JSON. bufferSizeLimits is TS-only (cppMirror.bufferSizeLimits).',
    '#pragma once',
    '',
    '#include <cstdint>',
    '',
    'namespace webgpu_limits {',
    '',
    `inline constexpr int kContractVersion = ${contract.version};`,
    '',
    '// minimumComputeLimits: the 14-entry compute bind group floor.',
    ...constants(contract.minimumComputeLimits),
    '',
    '// deepWorkgroupLimits: requested on top only when the adapter reports all three.',
    'namespace deep {',
    ...constants(contract.deepWorkgroupLimits),
    '}  // namespace deep',
    '',
    '}  // namespace webgpu_limits',
    '',
  ].join('\n');
}

function main(argv) {
  const contract = loadContract();
  const out = headerPath(contract);
  const want = renderHeader(contract);
  if (argv.includes('--check')) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (have !== want) {
      console.error(`❌ ${contract.cpp.header} is stale; run: npm run gen:webgpu-limits`);
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(out, want);
  console.log(`wrote ${contract.cpp.header}`);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { loadContract, renderHeader, headerPath, constName };
