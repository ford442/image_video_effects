#!/usr/bin/env node
/**
 * Bundle the layer compositor's WGSL (public/shaders/_compositor/*.wgsl, #1512 Part B)
 * into src/renderer/webgpu/compositorShaders.generated.ts.
 *
 * The compositor is part of the renderer, not the catalog: the app deploy does not
 * ship public/shaders and the storage sync never uploads `_` files, so the runtime
 * must never fetch these. The .wgsl files stay the editable source (naga-validated by
 * verify:naga-wasm); the renderer imports the generated strings.
 *
 * Usage: node scripts/gen-compositor-wgsl.mjs [--check]
 *   (none)  — write the module (committed; `npm run gen:compositor-wgsl`)
 *   --check — exit 1 if the committed module differs (verify:generated-sync runs the writer)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const COMPOSITOR_WGSL_DIR = path.join(ROOT, 'public', 'shaders', '_compositor');
export const COMPOSITOR_WGSL_MODULE = path.join(ROOT, 'src', 'renderer', 'webgpu', 'compositorShaders.generated.ts');

const constName = (file) => `${path.basename(file, '.wgsl').replace(/[^a-z0-9]+/gi, '_').toUpperCase()}_WGSL`;

export function renderModule(dir = COMPOSITOR_WGSL_DIR) {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.wgsl')).sort();
  const lines = [
    '// GENERATED by scripts/gen-compositor-wgsl.mjs from public/shaders/_compositor/*.wgsl.',
    '// Do not edit: change the .wgsl and run `npm run gen:compositor-wgsl`.',
    '// verify:generated-sync fails when this is stale.',
    '',
  ];
  for (const file of files) {
    const text = fs.readFileSync(path.join(dir, file), 'utf8');
    lines.push(`/** public/shaders/_compositor/${file} */`);
    lines.push(`export const ${constName(file)} = ${JSON.stringify(text)};`, '');
  }
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const next = renderModule();
  const current = fs.existsSync(COMPOSITOR_WGSL_MODULE) ? fs.readFileSync(COMPOSITOR_WGSL_MODULE, 'utf8') : null;
  if (check) {
    if (current !== next) {
      console.error(`${path.relative(ROOT, COMPOSITOR_WGSL_MODULE)} is stale: run npm run gen:compositor-wgsl`);
      process.exit(1);
    }
    console.log('compositor WGSL module is up to date');
    return;
  }
  if (current !== next) fs.writeFileSync(COMPOSITOR_WGSL_MODULE, next);
  console.log(`wrote ${path.relative(ROOT, COMPOSITOR_WGSL_MODULE)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
