#!/usr/bin/env node
/**
 * Print toolchain pin / compile flags from src/contracts/wasm_compile_flags.json.
 * Usage: node scripts/format-wasm-compile-flags.js [args|emsdk|output|variants|sources|compile-commands|compile-line] [--variant=asyncify|jspi]
 *   args             — one em++ argument per line (std, opt, use-port, -s flags [, -sJSPI_EXPORTS])
 *   emsdk            — pinned emsdk/emcc version
 *   output           — Emscripten JS output file name for the variant
 *   variants         — build variant names, one per line (build.sh loops over these)
 *   sources          — translation units (paths relative to wasm_renderer/), one per line
 *   compile-commands — write <repo>/compile_commands.json for clangd / CLion (gitignored)
 *   compile-line     — write reports/wasm_compile_line.txt (human dump, committed)
 *
 * The top-level graph is the ASYNCIFY fallback (variant "asyncify", default).
 * The `jspi` graph is the JSPI primary. build.sh / CMake / CI must never
 * spell -sASYNCIFY or -sJSPI themselves (verify:wasm-invariants).
 */
const fs = require('fs');
const path = require('path');

const CONTRACT_PATH = path.join(__dirname, '..', 'src', 'contracts', 'wasm_compile_flags.json');
const VARIANTS = ['asyncify', 'jspi'];

function loadContract(file = CONTRACT_PATH) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

/** Resolved { sFlags, jsOutputName, jspiExports } for one variant. */
function variantGraph(contract, variant) {
  if (variant === 'asyncify') {
    return { sFlags: contract.sFlags, jsOutputName: contract.jsOutputName, jspiExports: [] };
  }
  if (variant === 'jspi') {
    const j = contract.jspi;
    if (!j) throw new Error('wasm_compile_flags.json has no `jspi` graph');
    return { sFlags: j.sFlags, jsOutputName: j.jsOutputName, jspiExports: j.jspiExports };
  }
  throw new Error(`unknown variant "${variant}" (expected ${VARIANTS.join('|')})`);
}

function emccArgs(contract, variant) {
  const g = variantGraph(contract, variant);
  const args = [
    `-std=${contract.std}`,
    contract.opt,
    `--use-port=${contract.usePort}`,
    ...g.sFlags.map((f) => `-s${f}`),
  ];
  if (g.jspiExports.length > 0) {
    args.push(`-sJSPI_EXPORTS=${g.jspiExports.join(',')}`);
  }
  return args;
}

const ROOT = path.join(__dirname, '..');
const RENDERER_DIR = path.join(ROOT, 'wasm_renderer');
const COMPILE_COMMANDS_PATH = path.join(ROOT, 'compile_commands.json');
const COMPILE_LINE_PATH = path.join(ROOT, 'reports', 'wasm_compile_line.txt');

/**
 * Per-TU flags for IDE indexing. build.sh is single-pass (compile+link in one
 * em++), so there is no real per-TU command to capture — and passing
 * --use-port per TU is exactly the USE_WEBGPU leak build.sh avoids. Instead the
 * port's headers go on the include path (as CMake's headers target does) and
 * every -s flag stays at link time.
 */
function perTuArgs(contract, emCache) {
  return [
    `-std=${contract.std}`,
    contract.opt,
    `-I${RENDERER_DIR}`,
    `-I${path.join(emCache, 'ports', contract.usePort, `${contract.usePort}_pkg`, 'webgpu', 'include')}`,
  ];
}

function compileCommands(contract, emCache) {
  return contract.sources.map((src) => ({
    directory: RENDERER_DIR,
    file: path.join(RENDERER_DIR, src),
    arguments: ['em++', ...perTuArgs(contract, emCache), '-c', path.join(RENDERER_DIR, src)],
  }));
}

/** Human-readable dump of both link lines, repo-relative so it is stable across machines. */
function compileLineReport(contract) {
  const lines = [
    '# GENERATED by `npm run wasm:compile-commands` from src/contracts/wasm_compile_flags.json.',
    '# Do not edit. verify:wasm-invariants fails when this drifts from the contract.',
    '# EXPORTED_FUNCTIONS / EXPORTED_RUNTIME_METHODS come from src/contracts/wasm_exports.json.',
    '',
    `emsdk: ${contract.emsdkVersion}`,
    '',
  ];
  for (const variant of VARIANTS) {
    const out = variantGraph(contract, variant).jsOutputName;
    lines.push(`## ${variant} → public/wasm/${out} + ${out.replace(/\.js$/, '.wasm')}`);
    lines.push('em++ \\');
    for (const a of emccArgs(contract, variant)) lines.push(`  ${a} \\`);
    for (const src of contract.sources) lines.push(`  wasm_renderer/${src} \\`);
    lines.push('  -Iwasm_renderer \\');
    lines.push('  -sEXPORTED_FUNCTIONS=<wasm_exports.json functions> \\');
    lines.push('  -sEXPORTED_RUNTIME_METHODS=<wasm_exports.json runtime> \\');
    lines.push(`  -o wasm_renderer/build/${out}`);
    lines.push('');
  }
  lines.push('## per-TU (compile_commands.json, IDE indexing only — no --use-port, no -s)');
  lines.push(`em++ ${perTuArgs(contract, '$EM_CACHE').map((a) => a.replace(`${ROOT}/`, '')).join(' ')} -c wasm_renderer/<source>.cpp`);
  return `${lines.join('\n')}\n`;
}

module.exports = {
  CONTRACT_PATH,
  COMPILE_LINE_PATH,
  VARIANTS,
  loadContract,
  variantGraph,
  emccArgs,
  compileCommands,
  compileLineReport,
};

if (require.main === module) {
  const kind = process.argv[2] || 'args';
  const variantArg = process.argv.find((a) => a.startsWith('--variant='));
  const variant = variantArg ? variantArg.slice('--variant='.length) : 'asyncify';
  const contract = loadContract();
  try {
    if (kind === 'args') {
      process.stdout.write(`${emccArgs(contract, variant).join('\n')}\n`);
    } else if (kind === 'emsdk') {
      process.stdout.write(contract.emsdkVersion);
    } else if (kind === 'output') {
      process.stdout.write(variantGraph(contract, variant).jsOutputName);
    } else if (kind === 'variants') {
      process.stdout.write(`${VARIANTS.join('\n')}\n`);
    } else if (kind === 'sources') {
      process.stdout.write(`${contract.sources.join('\n')}\n`);
    } else if (kind === 'compile-commands') {
      // Same default as build.sh, which exports EM_CACHE=/tmp/emscripten_cache.
      const emCache = process.env.EM_CACHE || '/tmp/emscripten_cache';
      const cmds = compileCommands(contract, emCache);
      fs.writeFileSync(COMPILE_COMMANDS_PATH, `${JSON.stringify(cmds, null, 2)}\n`);
      fs.writeFileSync(COMPILE_LINE_PATH, compileLineReport(contract));
      console.log(`✅ ${path.relative(ROOT, COMPILE_COMMANDS_PATH)} (${cmds.length} TUs, EM_CACHE=${emCache})`);
      console.log(`✅ ${path.relative(ROOT, COMPILE_LINE_PATH)}`);
    } else if (kind === 'compile-line') {
      fs.writeFileSync(COMPILE_LINE_PATH, compileLineReport(contract));
      console.log(`✅ ${path.relative(ROOT, COMPILE_LINE_PATH)}`);
    } else {
      console.error('Usage: format-wasm-compile-flags.js [args|emsdk|output|variants|sources|compile-commands|compile-line] [--variant=asyncify|jspi]');
      process.exit(1);
    }
  } catch (err) {
    console.error(`❌ ${err.message}`);
    process.exit(1);
  }
}
